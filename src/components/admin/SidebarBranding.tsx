export const SidebarBranding: React.FC = () => {
  useEffect(() => {
    // 1. Hide [Untitled] headers dynamically
    const hideUntitledText = () => {
      const headings = document.querySelectorAll('h1, h2, .doc-header__title')
      headings.forEach(h => {
        const el = h as HTMLElement
        if (el.textContent?.trim() === '[Untitled]') {
          el.style.display = 'none'
          const headerElement = el.closest('.doc-header, .collection-edit__header, header') as HTMLElement
          if (headerElement) {
            headerElement.style.display = 'none'
          } else if (el.parentElement) {
            el.parentElement.style.display = 'none'
          }
        }
      })
    }

    // 2. Enhance sidebar navigation with single icons & floating tooltips for closed state
    const enhanceSidebarNav = () => {
      const navGroups = document.querySelectorAll('.nav-group, [class*="nav-group"]')

      navGroups.forEach(group => {
        const titleBtn = group.querySelector('.nav-group__toggle, .nav-group__title, button') as HTMLElement
        if (!titleBtn) return

        // Remove any custom injected group icons to ensure ONLY Payload's single native group icon shows
        const customGroupIcons = titleBtn.querySelectorAll('.te-group-icon')
        customGroupIcons.forEach(icon => icon.remove())

        const groupTitleText = titleBtn.textContent?.trim().toUpperCase() || ''

        // Set data attribute for floating tooltips in closed mode
        if (groupTitleText) {
          titleBtn.setAttribute('data-te-title', groupTitleText)
        }

        // Check if group contains the active route link
        const hasActiveLink = group.querySelector('.nav__link--active, .active, a[aria-current="page"]') !== null

        // Default closed state for non-active groups
        if (!hasActiveLink && !group.hasAttribute('data-te-initialized')) {
          group.setAttribute('data-te-initialized', 'true')
          if (titleBtn.getAttribute('aria-expanded') === 'true') {
            titleBtn.click()
          }
        }
      })

      // Inject icons & tooltips for individual nav links (ensuring strictly 1 icon per link)
      const navLinks = document.querySelectorAll('.nav__link, a[class*="nav__link"]')
      navLinks.forEach(link => {
        const a = link as HTMLAnchorElement
        const labelText = a.textContent?.trim() || ''

        if (labelText) {
          a.setAttribute('data-te-title', labelText)
        }

        // Clean up duplicate .te-link-icon elements to guarantee exactly 1 icon per link
        const teIcons = a.querySelectorAll('.te-link-icon')
        if (teIcons.length > 1) {
          for (let i = 1; i < teIcons.length; i++) {
            teIcons[i].remove()
          }
        } else if (teIcons.length === 0) {
          const href = a.getAttribute('href') || ''
          const linkKey = Object.keys(LINK_ICONS).find(k => href.includes(k))
          if (linkKey) {
            const iconSpan = document.createElement('span')
            iconSpan.className = 'te-link-icon'
            iconSpan.innerHTML = LINK_ICONS[linkKey]
            a.prepend(iconSpan)
          }
        }
      })
    }

    // Run initial execution
    hideUntitledText()
    enhanceSidebarNav()

    // MutationObserver to maintain single-icon state on navigation
    const observer = new MutationObserver(() => {
      hideUntitledText()
      enhanceSidebarNav()
    })

    observer.observe(document.body, { childList: true, subtree: true })
    return () => observer.disconnect()
  }, [])

  return (
    <div className="sidebar-branding-text" style={{
      position: 'absolute',
      top: '28px',
      left: '72px',
      color: 'var(--te-gold)',
      fontWeight: 800,
      fontSize: '12px',
      lineHeight: '1.4',
      letterSpacing: '1.5px',
      borderLeft: '2px solid rgba(176, 141, 87, 0.3)',
      paddingLeft: '14px',
      whiteSpace: 'nowrap',
      zIndex: 10,
      pointerEvents: 'none'
    }}>
      TEAM EYRIE <br /> ADMIN PANEL
    </div>
  )
}
